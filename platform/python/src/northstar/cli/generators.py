# ---- recipes (structured stub) --------------------------------------------------------


def plan_recipe(action: str, recipe: str) -> RecipePlan:
    """Return a structured, side-effect-free plan for a recipe add/remove request.

    Recipe application (registration, migrations, config writes) is owned by the
    distribution/installer runtime (docs/38) and is out of scope for this packet, so this
    reports an honest plan rather than a false success (NOT RUN != PASS).
    """
    if action not in ("add", "remove"):
        raise GeneratorError(f"invalid recipe action {action!r}: expected add|remove")
    validate_name(recipe)
    if action == "add":
        steps = (
            f"resolve recipe '{recipe}' from the signed catalog",
            "display requested permissions and compatibility",
            "apply declared files/config/module registration/migrations transactionally",
            "emit a change report and verification commands",
        )
    else:
        steps = (
            f"resolve installed recipe '{recipe}' and its ownership record",
            "compute reverse plan honoring declared removal behavior",
            "revert files/config/registration transactionally with evidence",
        )
    return RecipePlan(action, recipe, steps)
